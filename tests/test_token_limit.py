"""Exercise the hook against real temporary Git indexes, never the working repo."""
import os
from pathlib import Path
import subprocess
import tempfile
import unittest

HOOK = Path(__file__).resolve().parents[1] / ".githooks" / "pre-commit"


class TokenLimitTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.env = os.environ.copy()
        for key in list(self.env):
            if key.startswith("GIT_"):
                self.env.pop(key)
        self.git("init", "-q")
        self.git("config", "core.hooksPath", str(HOOK.parent))
        self.git("config", "user.name", "Hook Test")
        self.git("config", "user.email", "hook@example.invalid")

    def git(self, *args):
        return subprocess.run(["git", *args], cwd=self.root, env=self.env,
                              capture_output=True, check=True).stdout

    def write(self, name, content, stage=True):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        if stage:
            self.git("add", "--", name)

    def hook(self, ok=True):
        result = subprocess.run([str(HOOK)], cwd=self.root, env=self.env,
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0 if ok else 1, result.stderr)
        return result.stderr

    def test_exact_boundary_and_one_byte_over(self):
        self.write("source.py", b"x" * 20000)
        self.hook()
        self.write("source.py", b"x" * 20001)
        message = self.hook(ok=False)
        self.assertIn("5,000.25 tokens", message)
        self.assertIn("Split code by responsibility", message)
        self.assertIn("git diff --cached", message)

    def test_only_index_content_counts(self):
        self.write("source.py", b"x" * 20001)
        self.write("source.py", b"small", stage=False)
        self.hook(ok=False)
        self.git("add", "source.py")
        self.write("source.py", b"x" * 20001, stage=False)
        self.write("untracked.py", b"x" * 20001, stage=False)
        self.hook()

    def test_lockfiles_codegen_headers_assets_and_attributes(self):
        large = b"x" * 20001
        for name in ("package-lock.json", "pnpm-lock.yaml", "go.sum", "example.lock", "schema.pb.go"):
            self.write(name, large)
        self.write("output.py", b"# Generated by example\n" + large)
        self.write("asset.bin", b"\0" + large)
        self.write("generated/output.txt", large)
        self.write(".gitattributes", b"generated/** linguist-generated=true\n")
        self.hook()

    def test_unstaged_attribute_cannot_bypass(self):
        self.write("source.py", b"x" * 20001)
        self.write(".gitattributes", b"source.py linguist-generated=true\n", stage=False)
        self.hook(ok=False)
        self.git("add", ".gitattributes")
        self.hook()
        self.write(".gitattributes", b"", stage=False)
        self.hook()

    def test_unset_attribute_and_handwritten_mention_are_checked(self):
        self.write(".gitattributes", b"source.py -linguist-generated\n")
        self.write("source.py", b"# Do not edit without review\n" + b"x" * 20001)
        self.hook(ok=False)

    def test_unusual_names_and_multibyte_content(self):
        self.write("space and\nnewline.md", "é".encode() * 10001)
        self.assertIn("20,002 bytes", self.hook(ok=False))

    def test_real_commit_invokes_hook_and_deleted_files_are_skipped(self):
        self.write("source.py", b"small")
        self.git("-c", "commit.gpgsign=false", "commit", "-qm", "baseline")
        self.write("large.py", b"x" * 20001)
        result = subprocess.run(
            ["git", "-c", "commit.gpgsign=false", "commit", "-qm", "blocked"],
            cwd=self.root, env=self.env, capture_output=True,
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn(b"Commit blocked", result.stderr)
        self.git("rm", "-f", "large.py", "source.py")
        self.hook()


if __name__ == "__main__":
    unittest.main()
