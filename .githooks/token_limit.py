#!/usr/bin/env python3
"""Reject staged authored files above 5,000 estimated tokens (bytes / 4)."""
import argparse
import fnmatch
import os
from pathlib import PurePosixPath
import re
import subprocess
import sys
import tempfile

MAX_BYTES = 5000 * 4
LOCKFILES = {
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml",
    "bun.lock", "bun.lockb", "Cargo.lock", "Gemfile.lock", "Pipfile.lock",
    "poetry.lock", "uv.lock", "composer.lock", "packages.lock.json",
    "go.sum", ".terraform.lock.hcl", "flake.lock",
}
GENERATED_NAMES = ("*.min.js", "*.min.css", "*.js.map", "*.css.map", "*.pb.go", "*_pb2.py", "*_pb2.pyi")
ATTRS = ("linguist-generated", "generated", "token-limit-ignore")
GENERATED_HEADER = re.compile(
    rb"(?im)^[ \t]*(?://|#|/\*|\*|<!--|--|;)?[ \t]*"
    rb"(?:@generated\b|<auto-generated\b|code generated\b[^\r\n]*do not edit|"
    rb"(?:this file (?:is |was ))?(?:auto(?:matically)?[- ]generated|generated (?:by|from))\b)"
)


def git(*args, data=None, env=None):
    return subprocess.run(
        ["git", *args], input=data, stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, check=True, env=env,
    ).stdout


def resolve_revision(value):
    return git("rev-parse", "--verify", "--end-of-options", value + "^{commit}").strip()


def check_paths(paths, prefix, attributes_env=None):
    if not paths:
        return []
    raw = git("check-attr", "--cached", "-z", "--stdin", *ATTRS,
              data=b"\0".join(paths) + b"\0", env=attributes_env).split(b"\0")
    excluded = {
        raw[i] for i in range(0, len(raw) - 1, 3)
        if raw[i + 2] in (b"set", b"true", b"1")
    }
    violations = []
    for path in paths:
        name = PurePosixPath(os.fsdecode(path)).name
        if path in excluded or name in LOCKFILES or name.endswith(".lock"):
            continue
        if any(fnmatch.fnmatchcase(name, pattern) for pattern in GENERATED_NAMES):
            continue
        if git("cat-file", "-t", prefix + path).strip() == b"commit":
            continue  # Gitlink: the submodule has its own authored-file policy.
        blob = git("cat-file", "blob", prefix + path)
        if len(blob) <= MAX_BYTES:
            continue
        # Generated headers and binary assets are outside the authored-text policy.
        if b"\0" in blob or GENERATED_HEADER.search(blob[:8192]):
            continue
        violations.append((os.fsdecode(path), len(blob)))
    return violations


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", help="Base revision; merge-base used by default")
    parser.add_argument("--candidate", help="Candidate revision for CI")
    parser.add_argument("--direct", action="store_true", help="Compare push before/after directly")
    parser.add_argument("--initial", action="store_true", help="Validate all files on an initial push")
    args = parser.parse_args(argv)
    if bool(args.candidate) != bool(args.base or args.initial) or (args.base and args.initial):
        parser.error("revision mode requires --candidate and exactly one of --base or --initial")
    if args.direct and not args.base:
        parser.error("--direct requires --base")
    os.chdir(os.fsdecode(git("rev-parse", "--show-toplevel").rstrip(b"\n")))
    if args.candidate:
        candidate = resolve_revision(args.candidate)
        if args.initial:
            paths = git("ls-tree", "-rz", "--name-only", candidate).split(b"\0")
        else:
            base = resolve_revision(args.base)
            if not args.direct:
                base = git("merge-base", base, candidate).strip()
            paths = git("diff", "--name-only", "--diff-filter=ACMR", "-z", base, candidate, "--").split(b"\0")
        # Attributes come from the candidate, not the checked-out tree or index.
        with tempfile.TemporaryDirectory(prefix="harness-token-index-") as directory:
            env = os.environ.copy()
            env["GIT_INDEX_FILE"] = os.path.join(directory, "index")
            git("read-tree", candidate, env=env)
            violations = check_paths([p for p in paths if p], candidate + b":", env)
    else:
        paths = git("diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z").split(b"\0")
        violations = check_paths([p for p in paths if p], b":")
    if not violations:
        print("[PASS] token-limit: checked {} changed paths".format(len([p for p in paths if p])))
        return 0
    print("Commit blocked: authored files exceed 5,000 tokens (20,000 bytes).", file=sys.stderr)
    for path, size in violations:
        print(f"  {path!r}: {size:,} bytes / 4 = {size / 4:,.2f} tokens", file=sys.stderr)
    print(
        "\nHow to split files:\n"
        "  1. Split code by responsibility into focused modules; keep the original\n"
        "     entry point small and update imports and callers.\n"
        "  2. Split documentation by topic into linked pages with a short index.\n"
        "     Split tests by feature and move shared fixtures into helpers.\n"
        "  3. Keep EVERY resulting authored file at or below 20,000 bytes.\n"
        "  4. Run the relevant checks, stage all split files with git add, inspect\n"
        "     git diff --cached, and retry the commit. Unstaged edits do not count.\n"
        "For genuine generated output only, stage a .gitattributes rule such as\n"
        "  path/to/generated/** linguist-generated=true\n"
        "Do not mark handwritten files as generated to bypass this limit.",
        file=sys.stderr,
    )
    return 1


def cli():
    try:
        return main()
    except (OSError, subprocess.CalledProcessError) as error:
        print("Token-limit hook failed; commit blocked: {}".format(error), file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError):
            print(os.fsdecode(error.stderr), file=sys.stderr)
        return 1
